// Function declaration
function sayHello() {
    console.log('Hello World');
}

sayHello();

// Parameter
function greet(name) {
    console.log(`Hello ${name}`);
}

greet('Budi');
greet('Andi');

// Return
function add(a, b) {
    return a + b;
}

const result = add(10, 20);

console.log(result);
