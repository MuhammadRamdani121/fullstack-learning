// Array destructuring
const fruits = ["Apple", "Banana", "Orange"];
const [first, second, third] = fruits;

console.log(first);
console.log(second);
console.log(third);

// Object destructuring
const user = {
  name: "Budi",
  age: 20,
  city: "Jakarta",
};

const { name, age, city } = user;

console.log(name);
console.log(age);
console.log(city);
