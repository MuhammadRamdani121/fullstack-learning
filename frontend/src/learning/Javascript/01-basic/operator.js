// Arithmetic Operator
const a = 10;
const b = 3;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);

// Comparison Operator
console.log(10 > 5);
console.log(10 < 5);
console.log(10 === 10);
console.log(10 !== 5);

// Logical Operator
const isAdult = true;
const hasTicket = true;

console.log(isAdult && hasTicket);
console.log(isAdult || hasTicket);
console.log(!isAdult);
